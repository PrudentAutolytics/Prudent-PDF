'use strict';
const fs=require('fs'),path=require('path'),root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ok=(v,m)=>{if(!v){console.error('FAIL:',m);process.exitCode=1}else console.log('PASS:',m)};
const cfg=JSON.parse(read('staticwebapp.config.json'));
ok(cfg.routes.some(r=>r.route==='/profile'),'profile route exists');
ok(read('js/config.js').includes("PROFILE         : '/api/profile'"),'profile API configured');
ok(read('js/shell.js').includes("label: 'My Profile'"),'profile navigation exists');
const profile=read('api/profile/index.js');
ok(profile.includes('profile_picture')&&profile.includes('generateSessionToken'),'profile supports picture and refreshed signed identity');
ok(profile.includes('already in use'),'profile email uniqueness is enforced');
const history=read('api/jobs-list/index.js');
ok(history.includes('information_schema.columns')&&history.includes('stable core job schema'),'history tolerates optional production schema columns');
const gov=read('pages/governance.html');
ok(gov.includes('APP_CONFIG.FLOWS.GOVERNANCE')&&!gov.includes("api({type:'governance'"),'governance uses user-scoped API');
const govApi=read('api/governance/index.js');
ok(/j\.user_id\s*=\s*\$1/.test(govApi),'governance data is scoped to authenticated user');
if(process.exitCode)process.exit(process.exitCode);
console.log('Profile, history, and governance regression tests passed.');
